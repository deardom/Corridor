// Generates the execution evidence for the submission:
//   evidence/sandbox-log.jsonl   every audit entry from every scenario (hash-chained per scenario)
//   evidence/transcripts.md      human-readable transcript of each scenario
//   evidence/summary.json        pass/fail of each scenario's expectations + chain verification
// Usage: node scripts/run-scenarios.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCENARIOS } from "../src/scenarios.js";
import { runScenario } from "../src/runner.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "evidence");
mkdirSync(outDir, { recursive: true });

let jsonl = "";
let md = "# Corridor: sandbox execution evidence\n\nGenerated by `node scripts/run-scenarios.mjs` with the deterministic rule brain, so anyone can reproduce these logs exactly. All money movements are simulated in the sandbox ledger.\n\n";
const summary = [];

for (const sc of SCENARIOS) {
  const { session, transcript } = await runScenario(sc);
  for (const e of session.audit.entries) jsonl += JSON.stringify({ scenario: sc.id, ...e }) + "\n";
  const chain = session.audit.verify();
  md += `## ${sc.title}\n\n*${sc.feature}*  \nPersona: \`${sc.persona}\` · Expected: ${sc.expect}\n\n`;
  for (const r of transcript) {
    if (r.kind === "chat") {
      md += `**Student:** ${r.user}${r.attachments.length ? ` _(attached: ${r.attachments.join(", ")})_` : ""}\n\n`;
      md += `Tools: ${r.tools.map((t) => `\`${t.name}\` [${t.tier}] → ${t.status}`).join(", ") || "none"}\n\n`;
      md += `**Corridor:**\n\n${r.reply.split("\n").map((l) => "> " + l).join("\n")}\n\n`;
    } else {
      md += `**${r.kind.replace(/_/g, " ")}**${r.note ? ` (${r.note})` : ""}${r.tool ? `: \`${r.tool}\`` : ""}\n\n\`\`\`json\n${JSON.stringify(r.result ?? r.fired, null, 2).slice(0, 1800)}\n\`\`\`\n\n`;
    }
  }
  md += `Audit chain: ${chain.ok ? `✅ verified, ${chain.length} entries, head \`${chain.head.slice(0, 16)}…\`` : `❌ broken at ${chain.brokenAt}`}\n\nFinal sandbox state:\n\n\`\`\`json\n${JSON.stringify({ wallets: session.ledger.wallets, fxQuotaUsedUsd: session.ledger.fxQuotaUsedUsd, obligations: session.ledger.obligations.map((o) => `${o.label}: ${o.status}`), transactions: session.ledger.transactions.length }, null, 2)}\n\`\`\`\n\n---\n\n`;
  summary.push({ scenario: sc.id, title: sc.title, steps: transcript.length, auditEntries: session.audit.entries.length, chainVerified: chain.ok, transactions: session.ledger.transactions.length, statuses: transcript.map((r) => r.kind === "chat" ? r.tools.map((t) => `${t.name}:${t.status}`).join("|") : `${r.kind}:${r.result?.status ?? (r.fired ? r.fired.map((f) => f.proposal).join("|") : "")}`) });
}

writeFileSync(join(outDir, "sandbox-log.jsonl"), jsonl);
writeFileSync(join(outDir, "transcripts.md"), md);
writeFileSync(join(outDir, "summary.json"), JSON.stringify({ generatedWith: "rule brain (deterministic)", scenarios: summary }, null, 2));
console.log(JSON.stringify(summary, null, 2));
